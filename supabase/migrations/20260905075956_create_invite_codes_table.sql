/*
# Create invite_codes table for teacher registration

1. New Tables
- `invite_codes`
  - `id` (uuid, primary key)
  - `code` (text, unique, not null) — the invite code string
  - `created_by` (uuid, references auth.users) — which teacher generated it
  - `is_active` (boolean, default true) — whether the code is still usable
  - `used_by` (uuid, references auth.users, nullable) — which teacher used it to sign up
  - `created_at` (timestamptz, default now)

2. Security
- Enable RLS on `invite_codes`.
- Authenticated teachers can read codes they created.
- Authenticated teachers can insert new codes (generated by themselves).
- Authenticated teachers can update/deactivate their own codes.
- The signup screen reads the current active code via a SECURITY DEFINER function (anon-readable) so new teachers can validate their invite code before they have an account.

3. Notes
- The `get_active_invite_code()` function returns the most recently created active code, callable by anon (for signup validation).
- The `teacher_settings.invite_code` column is now superseded by this table but kept for backwards compatibility.
*/

CREATE TABLE IF NOT EXISTS invite_codes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code text UNIQUE NOT NULL,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  is_active boolean NOT NULL DEFAULT true,
  used_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE invite_codes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "select_own_invite_codes" ON invite_codes;
CREATE POLICY "select_own_invite_codes" ON invite_codes FOR SELECT
  TO authenticated USING (auth.uid() = created_by);

DROP POLICY IF EXISTS "insert_own_invite_codes" ON invite_codes;
CREATE POLICY "insert_own_invite_codes" ON invite_codes FOR INSERT
  TO authenticated WITH CHECK (auth.uid() = created_by);

DROP POLICY IF EXISTS "update_own_invite_codes" ON invite_codes;
CREATE POLICY "update_own_invite_codes" ON invite_codes FOR UPDATE
  TO authenticated USING (auth.uid() = created_by) WITH CHECK (auth.uid() = created_by);

DROP POLICY IF EXISTS "delete_own_invite_codes" ON invite_codes;
CREATE POLICY "delete_own_invite_codes" ON invite_codes FOR DELETE
  TO authenticated USING (auth.uid() = created_by);

-- Function to get the current active invite code (anon-readable for signup validation)
CREATE OR REPLACE FUNCTION get_active_invite_code()
RETURNS text
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT code FROM invite_codes WHERE is_active = true ORDER BY created_at DESC LIMIT 1;
$$;

GRANT EXECUTE ON FUNCTION get_active_invite_code() TO anon, authenticated;

-- Seed an initial code from the existing teacher_settings value
INSERT INTO invite_codes (code, is_active)
SELECT invite_code, true
FROM teacher_settings
WHERE id = 1 AND invite_code IS NOT NULL
AND NOT EXISTS (SELECT 1 FROM invite_codes WHERE code = teacher_settings.invite_code)
LIMIT 1;
